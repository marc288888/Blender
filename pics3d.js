const PIC_FLAT = Object.assign({}, PIC);

/* An entry can end in "|degrees" to turn the picture's colour round the
   colour wheel, so it matches the story (yellow yo-yo, red socks ...). */
function setPictureStyle(style) {
  for (const k of Object.keys(PIC3D)) {
    const [file, hue] = PIC3D[k].split("|");
    const tint = hue ? ' style="filter:hue-rotate(' + hue + 'deg)"' : "";
    PIC[k] = style === "flat"
      ? PIC_FLAT[k]
      : '<image href="pics/' + file + '" x="0" y="0" width="100" height="100"' + tint + '/>';
  }
}
setPictureStyle("3d");
